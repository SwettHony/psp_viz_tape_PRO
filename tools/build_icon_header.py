"""Generate icon_patch.h, the cassette-icon patch built into the kernel plugin.

The plugin applies it on the PSP to the stock flash0 resource, so users never
need to copy that file off the console. Run with --check to verify the
committed header matches assets/visualizer-icon.patch.json.
"""
import base64
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
patch = json.loads((root/'assets/visualizer-icon.patch.json').read_text())
header = (root/'icon_resource.h').read_text()
assert patch['format'] == 'viz-tape-icon-patch-1'
assert patch['output_size'] == int(re.search(r'#define TAPE_ICON_SIZE (\d+)u', header)[1])

ops, blob = [], b''
for operation in patch['operations']:
    if 'copy' in operation:
        offset, length = operation['copy']
        ops.append((1, offset, length))
    else:
        data = base64.b64decode(operation['data'], validate=True)
        ops.append((0, len(blob), len(data)))
        blob += data

lines = [
    '/* Generated by tools/build_icon_header.py from assets/visualizer-icon.patch.json.',
    ' * Cassette selector icon, applied on the PSP to the stock 6.61',
    ' * flash0:/vsh/resource/visualizer_plugin.rco. Copy operations take bytes from',
    ' * that file; data operations take them from tape_patch_data. Only the new',
    ' * icon image and the rebuilt resource header are stored here. */',
    '#ifndef VIZ_TAPE_ICON_PATCH_H',
    '#define VIZ_TAPE_ICON_PATCH_H',
    f"#define TAPE_PATCH_SOURCE_SIZE {patch['source_size']}u",
    f'#define TAPE_PATCH_OPS {len(ops)}u',
    'static const TapePatchOp tape_patch_ops[TAPE_PATCH_OPS] = {',
]
lines += [f'    {{ {kind}, {offset}u, {length}u }},' for kind, offset, length in ops]
lines += ['};', f'static const unsigned char tape_patch_data[{len(blob)}] = {{']
for i in range(0, len(blob), 16):
    lines.append('    ' + ', '.join(f'0x{b:02x}' for b in blob[i:i+16]) + ',')
lines += ['};', '#endif', '']
text = '\n'.join(lines)

target = root/'icon_patch.h'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != text:
        sys.exit('icon_patch.h is out of date: run python3 tools/build_icon_header.py')
    print('Icon patch header matches assets/visualizer-icon.patch.json.')
else:
    target.write_text(text)
    print(f'Wrote icon_patch.h ({len(ops)} operations, {len(blob)} data bytes).')
